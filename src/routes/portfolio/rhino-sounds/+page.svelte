<div>
	<h1>Sound Design - Rhinoceros</h1>
	<p>
		I was in charge of doing sound design for a senior thesis production of <i>Rhinoceros</i>. In
		the real world, rhinos do not make very much noise, so I had to take some creative liberties and
		make them sound large and scary even when you don't actually see them on stage.
	</p>

	<p>
		To make the sounds, I used a mixture of different animal sounds, including horses, pigs, and
		elephants.
	</p>
</div>
